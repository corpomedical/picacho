// Finds "succeeded" rows whose files are gone, and stages the fix.
//
// A storage cleanup removed files while their generation rows kept status
// "succeeded" — so History showed a healthy tile over a
// 404, and the player span forever (operator report, 2026-09-11: "the video
// loads forever"). A row whose file the owner deleted should read exactly
// like a row deleted in the app: soft-deleted — deleted_at set, ledger kept,
// hidden from History — which is what deleteGeneration leaves behind.
//
// Reads with the service role; WRITES NOTHING. It prints a report and writes
// supabase/pending/soft-delete-missing-files.sql with the explicit row ids
// for the operator to run. Community posts whose snapshotted media is gone
// are reported too (their fix — delete the post — is the operator's call and
// is included commented out).
//
//   NEXT_PUBLIC_SITE_URL=https://picacho.ai npx tsx scripts/sweep-missing-files.mjs
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL(".", import.meta.url).pathname;
const env = Object.fromEntries(
  readFileSync(`${here}../.env.local`, "utf8").split("\n")
    .filter((l) => l.includes("=") && !l.startsWith("#"))
    .map((l) => { const i = l.indexOf("="); return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")]; }),
);
const base = env.NEXT_PUBLIC_SUPABASE_URL, key = env.SUPABASE_SERVICE_ROLE_KEY;
const ORIGIN = process.env.NEXT_PUBLIC_SITE_URL || "https://picacho.ai";
const H = { apikey: key, authorization: `Bearer ${key}` };

const abs = (u) => (u.startsWith("http") ? u : `${ORIGIN}${u}`);
const gone = async (u) => {
  for (let attempt = 1; ; attempt++) {
    try {
      const r = await fetch(abs(u), { method: "HEAD" });
      if (r.status === 404) return true;
      if (r.ok || r.status === 308 || r.status === 301) return false;
      return false; // any other status is not proof the file is gone
    } catch (e) {
      if (attempt < 4) { await new Promise((s) => setTimeout(s, 1500 * attempt)); continue; }
      console.error(`network failure checking ${u.slice(0, 80)}: ${e?.cause?.code ?? e.message}`);
      process.exit(3);
    }
  }
};

const rows = await (await fetch(
  `${base}/rest/v1/generations?select=id,user_id,created_at,content_type,result_url,prompt_input&status=eq.succeeded&deleted_at=is.null&result_url=not.is.null&order=created_at.desc&limit=1000`,
  { headers: H },
)).json();
const missing = [];
let n = 0;
for (const r of rows) {
  // Mock-era rows ("mock://…") have no file to check and History renders
  // its simulated-result state for them; only our media URLs and provider
  // CDN URLs are real files.
  const checkable = r.result_url.startsWith("/api/media/") || r.result_url.startsWith("http");
  if (checkable && (await gone(r.result_url))) missing.push(r);
  process.stderr.write(`\r  ${++n}/${rows.length} (${missing.length} missing)`);
}
process.stderr.write("\n");

const posts = await (await fetch(`${base}/rest/v1/community_posts?select=id,generation_id,media_url&limit=1000`, { headers: H })).json();
const deadPosts = [];
for (const p of Array.isArray(posts) ? posts : []) {
  if (p.media_url && (await gone(p.media_url))) deadPosts.push(p);
}

console.log(`\n${rows.length} succeeded rows checked; ${missing.length} with the file gone; ${deadPosts.length} community post(s) with dead media`);
for (const r of missing) console.log(`  ${r.created_at.slice(0, 16)} ${r.content_type.padEnd(5)} ${r.id} u=${r.user_id.slice(0, 8)} ${JSON.stringify(r.prompt_input ?? "").slice(0, 60)}`);

if (missing.length) {
  const sql = `-- Rows whose files are gone read as deleted, because they are.
--
-- A storage cleanup (the 9 September purge, and possibly earlier ones)
-- removed these rows' files while the rows kept status "succeeded", so History showed a healthy tile over a 404
-- and the player span forever (operator report, 2026-09-11). Soft-deleting
-- mirrors what deleteGeneration leaves for a row the owner removes in the
-- app: deleted_at set, the ledger untouched, hidden from History and from
-- every gallery. Generated by scripts/sweep-missing-files.mjs, which
-- HEAD-checked every succeeded row's file on ${new Date().toISOString().slice(0, 10)};
-- re-run it any time to regenerate this list.

update public.generations
   set deleted_at = now()
 where deleted_at is null
   and id in (
${missing.map((r, i) => `     '${r.id}'${i < missing.length - 1 ? "," : " "}  -- ${r.created_at.slice(0, 10)} ${r.content_type}`).join("\n")}
   );

-- Verify: select count(*) from generations where deleted_at is null and id in (…) -> 0 rows.
${deadPosts.length ? `\n-- Community posts snapshotting dead media (operator's call — a delete removes\n-- them from the public feed):\n${deadPosts.map((p) => `-- delete from public.community_posts where id = '${p.id}';`).join("\n")}` : ""}`;
  writeFileSync(`${here}../supabase/pending/soft-delete-missing-files.sql`, sql + "\n");
  console.log(`\nwrote supabase/pending/soft-delete-missing-files.sql (${missing.length} rows)`);
}
